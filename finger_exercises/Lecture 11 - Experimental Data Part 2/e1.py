# that describes the data. This means that knowing the physical phenomenon or
# event that is being modeled is extremely important. For each of the following
# data/phenomena/events, describe what type of model (linear, quadratic, other)
# you would use to describe the underlying phenomena.
#
#
# Hourly temperature from 7am to 7pm
#
# ans: A quadratic model would likely be appropriate for modeling hourly
# temperature from 7am to 7pm, as temperature typically follows a parabolic
# pattern throughout the day, rising in the morning, peaking in the afternoon,
# and then declining in the evening.
#
# 
# Gravitational force on an object as mass increases
#
# ans: A linear model would be appropriate for modeling the gravitational force
# on an object as mass increases, as gravitational force is directly
# proportional to mass according to Newton's law of universal gravitation (F =
# G * (m1 * m2) / r^2), where F is the gravitational force, G is the
# gravitational constant, m1 and m2 are the masses of the objects, and r is the
# distance between them.
#
#
# Displacement of a mass on a hanging spring from the ceiling
#
# ans: Other
#
