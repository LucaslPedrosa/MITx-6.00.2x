# 1. He catches the flu in September, October and November.
# Calculation: (1/10) * (1/10) * (1/10)
# Answer: 1/1000

# 2. He catches the flu in September and then again in November, but not in October.
# Calculation: (1/10) * (9/10) * (1/10)
# Answer: 9/1000

# 3. He catches the flu exactly once in the three months from September through November.
# Combinations: (F, N, N), (N, F, N), or (N, N, F)
# Calculation: 3 * (1/10 * 9/10 * 9/10) = 3 * (81/1000)
# Answer: 243/1000

# 4. He catches the flu in two or more of the three months from September through November.
# This includes exactly 2 months OR exactly 3 months.
# Exactly 2: 3 * (1/10 * 1/10 * 9/10) = 27/1000
# Exactly 3: (1/10 * 1/10 * 1/10) = 1/1000
# Total: 27/1000 + 1/1000 = 28/1000
# Answer: 7/250
